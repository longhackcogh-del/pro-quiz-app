const { test } = require('node:test');
const assert = require('node:assert/strict');
const express = require('express');
const { createGoogleAuth } = require('../server/google-auth');

test('Google OAuth: missing config, state/PKCE, verified identity, cookie session, logout and provider failure', async t => {
  const env = {};
  let fail = false;
  let verified = true;
  let time = Date.now();
  const requests = [];
  const app = express();
  app.use(createGoogleAuth({ env, now: () => time, request: async (url, options) => {
    requests.push({url, options});
    if (fail) return {ok:false};
    return {ok:true, json:async () => url.endsWith('/token') ? {access_token:'test-token'} : {sub:'google-test-user',email:'test@example.com',name:'Test User',email_verified:verified}};
  }}));
  app.get('/public-check', (_req,res) => res.send('public'));
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.on('listening',resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const base = `http://127.0.0.1:${server.address().port}`;
  const request = (route, options={}) => fetch(base+route,{redirect:'manual',...options});
  let response = await request('/api/auth/status');
  assert.equal((await response.json()).configured,false);
  assert.equal(response.headers.get('cache-control'),'no-store');
  assert.equal((await request('/public-check')).headers.get('cache-control'),null);
  assert.equal((await request('/auth/google')).status,503);
  Object.assign(env,{GOOGLE_CLIENT_ID:'test-client',GOOGLE_CLIENT_SECRET:'test-secret',GOOGLE_REDIRECT_URI:base+'/auth/google/callback'});
  env.GOOGLE_REDIRECT_URI = 'http://localhost:'+server.address().port+'/auth/google/callback';
  response = await request('/auth/google');
  assert.equal(response.status,303);
  assert.equal(response.headers.get('location'),'http://localhost:'+server.address().port+'/auth/google');
  assert.equal(response.headers.get('set-cookie'),null);
  env.GOOGLE_REDIRECT_URI = base+'/auth/google/callback';
  response = await request('/api/auth/status');
  assert.equal((await response.json()).loginUrl,base+'/auth/google');
  response = await request('/auth/google');
  const url = new URL(response.headers.get('location'));
  assert.equal(url.origin,'https://accounts.google.com');
  assert.equal(url.searchParams.get('scope'),'openid email profile');
  assert.equal(url.searchParams.get('prompt'),'select_account');
  assert.equal(url.searchParams.get('code_challenge_method'),'S256');
  assert.ok(!url.href.includes('test-secret'));
  const flowCookie = response.headers.get('set-cookie').split(';')[0];
  const state = url.searchParams.get('state');
  response = await request('/auth/google/callback?code=test&state=bad',{headers:{cookie:flowCookie}});
  assert.equal(response.headers.get('location'),'/?auth=invalid_state');
  assert.equal(requests.length,0);
  response = await request(`/auth/google/callback?code=test&state=${state}`,{headers:{cookie:flowCookie}});
  assert.equal(response.headers.get('location'),'/?auth=success');
  assert.equal(requests[0].options.body.get('client_secret'),'test-secret');
  assert.ok(requests[0].options.body.get('code_verifier'));
  const session = response.headers.getSetCookie().find(cookie => cookie.startsWith('quiz_session='));
  assert.ok(session.includes('HttpOnly'));
  assert.ok(session.includes('SameSite=Lax'));
  assert.ok(!session.includes('test-token'));
  response = await request('/api/auth/status',{headers:{cookie:session.split(';')[0]}});
  const signedIn = await response.json();
  assert.equal(signedIn.user.id,'google-test-user');
  assert.equal(new Date(signedIn.expiresAt).getTime(),time+8*60*60*1000);
  response = await request('/api/auth/status',{headers:{cookie:'quiz_session=forged'}});
  assert.equal((await response.json()).user,null);
  response = await request(`/auth/google/callback?code=test&state=${state}`,{headers:{cookie:flowCookie}});
  assert.equal(response.headers.get('location'),'/?auth=invalid_state');
  assert.equal((await request('/api/auth/logout',{method:'POST',headers:{cookie:session,origin:'https://untrusted.example'}})).status,403);
  assert.equal((await request('/api/auth/logout',{method:'POST',headers:{cookie:session,origin:base}})).status,204);
  response = await request('/api/auth/status',{headers:{cookie:session.split(';')[0]}});
  assert.equal((await response.json()).user,null);
  for (const mode of ['provider-failure','unverified-email','cancelled']) {
    fail = mode === 'provider-failure';
    verified = mode !== 'unverified-email';
    response = await request('/auth/google');
    const nextState = new URL(response.headers.get('location')).searchParams.get('state');
    const cookie = response.headers.get('set-cookie').split(';')[0];
    response = await request(`/auth/google/callback?${mode === 'cancelled' ? 'error=access_denied' : 'code=test'}&state=${nextState}`,{headers:{cookie}});
    assert.equal(response.headers.get('location'),mode === 'cancelled' ? '/?auth=cancelled' : '/?auth=failed');
    assert.ok(!response.headers.getSetCookie().some(value => value.startsWith('quiz_session=')));
  }
  response = await request('/auth/google');
  const expiredState = new URL(response.headers.get('location')).searchParams.get('state');
  const expiredCookie = response.headers.get('set-cookie').split(';')[0];
  const beforeExpiry = requests.length;
  time += 6*60*1000;
  response = await request(`/auth/google/callback?code=test&state=${expiredState}`,{headers:{cookie:expiredCookie}});
  assert.equal(response.headers.get('location'),'/?auth=invalid_state');
  assert.equal(requests.length,beforeExpiry);
  fail=false; verified=true;
  response = await request('/auth/google');
  const validState = new URL(response.headers.get('location')).searchParams.get('state');
  const validCookie = response.headers.get('set-cookie').split(';')[0];
  response = await request(`/auth/google/callback?code=test&state=${validState}`,{headers:{cookie:validCookie}});
  const newSession = response.headers.getSetCookie().find(value=>value.startsWith('quiz_session=')).split(';')[0];
  time += 8*60*60*1000+1;
  response = await request('/api/auth/status',{headers:{cookie:newSession}});
  assert.equal((await response.json()).user,null);
  env.GOOGLE_REDIRECT_URI = 'invalid';
  response = await request('/api/auth/status');
  assert.equal((await response.json()).configured,false);
  assert.equal((await request('/auth/google')).status,503);
  assert.equal((await request('/api/auth/logout',{method:'POST',headers:{origin:base}})).status,204);
});
