const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path');
test('Security: no early answers, cross-site writes blocked, private files hidden and safe headers',async t=>{
 const directory=fs.mkdtempSync(path.join(os.tmpdir(),'quiz-security-'));
 process.env.DATABASE_FILE=path.join(directory,'test.sqlite');
 const {loadAuthenticatedApp,authenticatedFetch}=require('./auth-client');
 const app=loadAuthenticatedApp(),db=require('../server/database');
 const server=app.listen(0,'127.0.0.1');await new Promise(resolve=>server.on('listening',resolve));
 const base='http://127.0.0.1:'+server.address().port;
 t.after(async()=>{await new Promise(resolve=>server.close(resolve));db.close();fs.rmSync(directory,{recursive:true,force:true});});
 const fetch=await authenticatedFetch(base);
 const request=async(route,body,method='POST',extra={})=>{const r=await fetch(base+route,{...(body!==undefined?{method,body:JSON.stringify(body)}:{}),headers:{'Content-Type':'application/json',...extra}});return {status:r.status,data:r.status===204?null:await r.json()};};
 for(const route of ['/.env','/.git/config','/data/pro-quiz.sqlite','/server/database.js'])assert.equal((await fetch(base+route)).status,404);
 const page=await fetch(base+'/');assert.equal(page.headers.get('x-powered-by'),null);assert.equal(page.headers.get('x-frame-options'),'DENY');assert.equal(page.headers.get('x-content-type-options'),'nosniff');
 assert.equal((await request('/api/questions/import',{questions:[]},'POST',{Origin:'https://attacker.example'})).status,403);
 assert.equal((await request('/api/auth/logout',{},'POST',{'Sec-Fetch-Site':'cross-site'})).status,403);
 const imported=await request('/api/questions/import',{questions:['First','Second'].map(prompt=>({prompt,options:['a','b','c','d'],answerIndex:1,confirmed:true}))},'POST',{Origin:base});
 assert.equal(imported.status,201);
 const attempt=(await request('/api/attempts',{})).data;
 assert.ok(attempt.questions.every(q=>!Object.hasOwn(q,'answerIndex')));
 for(const route of ['/api/attempts/active','/api/attempts/'+attempt.id])assert.ok((await request(route)).data.questions.every(q=>!Object.hasOwn(q,'answerIndex')));
 const first=attempt.questions[0];
 const answered=(await request('/api/attempts/'+attempt.id+'/answer',{questionId:first.id,selectedIndex:0,currentIndex:0},'PATCH')).data;
 assert.equal(answered.questions.find(q=>q.id===first.id).answerIndex,1);
 assert.ok(!Object.hasOwn(answered.questions.find(q=>q.id!==first.id),'answerIndex'));
 const finished=(await request('/api/attempts/'+attempt.id+'/submit',{score:999})).data;
 assert.equal(finished.score,0);assert.ok(finished.questions.every(q=>q.answerIndex===1));
 assert.equal((await fetch(base+'/api/questions')).headers.get('cache-control'),'no-store');
});
