const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
test('Account isolation, legacy ownership and private question sets',async t=>{
  const directory=fs.mkdtempSync(path.join(os.tmpdir(),'quiz-accounts-'));
  process.env.DATABASE_FILE=path.join(directory,'test.sqlite');
  process.env.LEGACY_OWNER_EMAIL='owner@example.com';
  const {loadAuthenticatedApp,authenticatedFetch}=require('./auth-client');
  const app=loadAuthenticatedApp(),db=require('../server/database');
  const server=app.listen(0,'127.0.0.1');await new Promise(resolve=>server.on('listening',resolve));
  t.after(async()=>{await new Promise(resolve=>server.close(resolve));db.close();fs.rmSync(directory,{recursive:true,force:true});});
  const base='http://127.0.0.1:'+server.address().port;
  const legacy=Number(db.prepare("INSERT INTO questions (prompt,source_text) VALUES ('legacy','legacy')").run().lastInsertRowid);
  const b=await authenticatedFetch(base,'user-b','other@example.com');
  const request=async(fetcher,route,body,method='POST',headers={})=>{
    const response=await fetcher(base+route,{...(body!==undefined?{method,body:JSON.stringify(body)}:{}),headers:{'Content-Type':'application/json',...headers}});
    return {status:response.status,data:response.status===204 ? null : await response.json()};
  };
  assert.equal((await fetch(base+'/api/questions')).status,401);
  assert.deepEqual((await request(b,'/api/questions')).data,[]);
  assert.equal(db.prepare('SELECT owner_id FROM questions WHERE id=?').get(legacy).owner_id,null);
  const a=await authenticatedFetch(base,'user-a','owner@example.com');
  assert.equal((await request(a,'/api/questions')).data[0].id,legacy);
  assert.equal(db.prepare('SELECT owner_id FROM questions WHERE id=?').get(legacy).owner_id,'user-a');
  const imported=await request(b,'/api/questions/import',{questions:[{prompt:'Private B',options:['a','b','c','d'],answerIndex:0,confirmed:true,owner_id:'user-a'}]});
  assert.equal(imported.status,201);const q=imported.data.imported[0].id;
  assert.equal((await request(a,'/api/questions/'+q)).status,404);
  assert.equal((await request(a,'/api/questions/'+q,{},'PATCH')).status,404);
  assert.equal((await request(a,'/api/questions/'+q,{},'DELETE')).status,404);
  const set=(await request(b,'/api/question-sets',{name:'Chapter 1'})).data;
  assert.deepEqual((await request(a,'/api/question-sets')).data,[]);
  assert.equal((await request(a,'/api/question-sets/'+set.id,{name:'Stolen'},'PATCH')).status,404);
  assert.equal((await request(a,'/api/question-sets/contents/move',{questionIds:[legacy],setId:set.id},'PATCH')).status,404);
  assert.equal((await request(b,'/api/question-sets/contents/move',{questionIds:[q,legacy],setId:set.id},'PATCH')).status,404);
  assert.equal((await request(b,'/api/question-sets/contents/move',{questionIds:[q],setId:set.id},'PATCH')).status,200);
  assert.equal((await request(b,'/api/questions/'+q)).data.setId,set.id);
  assert.equal((await request(b,'/api/question-sets')).data[0].questionCount,1);
  const attempt=(await request(b,'/api/attempts',{questionIds:[q]})).data;
  assert.equal((await request(a,'/api/attempts/'+attempt.id)).status,404);
  assert.equal((await request(a,'/api/attempts/'+attempt.id+'/answer',{questionId:q,selectedIndex:1,currentIndex:0},'PATCH')).status,404);
  assert.equal((await request(a,'/api/attempts/'+attempt.id+'/submit',{})).status,404);
  assert.equal((await request(a,'/api/attempts/'+attempt.id+'/retry-wrong',{})).status,404);
  assert.equal((await request(a,'/api/attempts',{questionIds:[legacy,q]})).status,400);
  assert.equal((await request(b,'/api/questions',undefined,'GET',{'X-Quiz-Account':'user-a'})).status,409);
  assert.equal((await request(b,'/api/question-sets/'+set.id,{name:'Renamed'},'PATCH')).status,200);
  assert.equal((await request(b,'/api/question-sets/'+set.id,{},'DELETE')).status,200);
  assert.equal((await request(b,'/api/questions/'+q)).data.setId,null);
  await request(a,'/api/questions/all',{},'DELETE');
  assert.equal((await request(b,'/api/questions')).data.length,1);
  await request(a,'/api/auth/logout',{});
  assert.equal((await request(a,'/api/questions')).status,401);
});
