const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const os=require('node:os');

test('Wrong review includes answered mistakes before submit, excludes unanswered, and tracks corrections',async t=>{
  const directory=fs.mkdtempSync(path.join(os.tmpdir(),'pro-quiz-wrong-'));
  process.env.DATABASE_FILE=path.join(directory,'test.sqlite');
  const app=require('./auth-client').loadAuthenticatedApp();const db=require('../server/database');
  const server=app.listen(0,'127.0.0.1');await new Promise(resolve=>server.on('listening',resolve));
  const base=`http://127.0.0.1:${server.address().port}`;
  const fetch = await require('./auth-client').authenticatedFetch(base);
  t.after(async()=>{await new Promise(resolve=>server.close(resolve));db.close();const target=path.resolve(directory);if(path.dirname(target)===path.resolve(os.tmpdir())&&path.basename(target).startsWith('pro-quiz-wrong-'))fs.rmSync(target,{recursive:true,force:true});});
  const request=async(route,body,method='POST')=>{const r=await fetch(base+route,body!==undefined?{method,headers:{'Content-Type':'application/json'},body:JSON.stringify(body)}:undefined);return {status:r.status,data:await r.json()};};
  await request('/api/questions/import',{questions:['First','Second','Third'].map(prompt=>({prompt,options:['A text','B text','C text','D text'],answerIndex:2,confirmed:true,sourceText:prompt}))});
  const attempt=(await request('/api/attempts',{})).data;
  const [wrong,correct,unanswered]=attempt.questions;
  await request(`/api/attempts/${attempt.id}/answer`,{questionId:wrong.id,selectedIndex:0,currentIndex:0},'PATCH');
  await request(`/api/attempts/${attempt.id}/answer`,{questionId:correct.id,selectedIndex:2,currentIndex:1},'PATCH');
  let history=(await request('/api/wrong-answers')).data;
  assert.equal(history.length,1);assert.equal(history[0].id,wrong.id);assert.equal(history[0].attemptStatus,'in_progress');
  assert.equal((await request('/api/stats')).data.wrong,1);
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM wrong_answers').get().n,0);
  const retry=(await request(`/api/attempts/${attempt.id}/retry-wrong`,{})).data;
  assert.equal(retry.total,1);assert.equal(retry.questions[0].id,wrong.id);assert.equal(retry.questions[0].selectedIndex,null);
  assert.equal((await request(`/api/attempts/${attempt.id}`)).data.status,'in_progress');
  assert.equal((await request(`/api/attempts/${attempt.id}`)).data.questions.find(q=>q.id===unanswered.id).selectedIndex,null);
  assert.ok((await(await fetch(base+'/api/wrong-answers/export')).text()).includes(wrong.prompt));
  await request(`/api/attempts/${attempt.id}/answer`,{questionId:wrong.id,selectedIndex:2,currentIndex:0},'PATCH');
  assert.equal((await request('/api/wrong-answers')).data.length,0);
  assert.equal((await request(`/api/attempts/${attempt.id}/retry-wrong`,{})).status,400);
  assert.equal((await request('/api/stats')).data.wrong,0);
  await request(`/api/attempts/${attempt.id}/answer`,{questionId:wrong.id,selectedIndex:0,currentIndex:0},'PATCH');
  await request(`/api/attempts/${attempt.id}/submit`,{});
  history=(await request('/api/wrong-answers')).data;
  assert.equal(history.length,2);assert.ok(history.every(q=>q.attemptStatus==='completed'));
  assert.deepEqual(history.map(q=>q.id).sort(),[wrong.id,unanswered.id].sort());
  assert.equal((await request(`/api/attempts/${attempt.id}/retry-wrong`,{})).data.total,2);
  await request(`/api/questions/${wrong.id}/content`,{prompt:'Edited question',options:['1','2','3','4']},'PATCH');
  const available=(await request(`/api/attempts/${attempt.id}/retry-wrong`,{})).data;
  assert.equal(available.total,1);assert.equal(available.questions[0].id,unanswered.id);
  assert.equal((await request('/api/attempts/999999/retry-wrong',{})).status,404);
});
